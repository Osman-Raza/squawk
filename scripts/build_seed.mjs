#!/usr/bin/env node
// Builds seed/seed.sql from an extracted NGAFID folder (manifest.json + flight CSVs).
// Uses the exact same engine as the Worker, so seeded data and live uploads are scored identically.
//
//   node scripts/build_seed.mjs data/ngafid [--keep 3] [--out seed/seed.sql]
import fs from "node:fs";
import path from "node:path";
import { parseFlightCsv, computeFeatures, fleetBaseline, assessAircraft } from "../src/engine.js";

const args = process.argv.slice(2);
const dir = args.find((a) => !a.startsWith("--")) || "data/ngafid";
const opt = (name, def) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : def;
};
const KEEP = +opt("keep", 3);
const OUT = opt("out", "seed/seed.sql");
const MODEL = opt("model", "Piston single, NGAFID fleet");

const manifest = JSON.parse(fs.readFileSync(path.join(dir, "manifest.json"), "utf8"));
const step = manifest.step_seconds || 1;

// 1. features for every flight
const planes = manifest.aircraft.map((a) => ({
  ...a,
  flights: a.flights.map((f) => {
    const text = fs.readFileSync(path.join(dir, f.csv), "utf8");
    const parsed = parseFlightCsv(text, 100000);
    // CSVs carry "# step_seconds=N"; fall back to the manifest for older extracts.
    const secs = text.includes("step_seconds") ? parsed.sampleStep : step * parsed.sampleStep;
    return { ...f, features: computeFeatures(parsed.rows, secs) };
  }),
}));

// 2. score repair cases against the full fleet, keep the strongest real signals for the demo
const scoreAll = (list) => {
  const base = fleetBaseline(list.flatMap((p) => p.flights.filter((f) => !f.is_future).map((f) => f.features)));
  return list.map((p) => ({ p, as: assessAircraft(p.flights.filter((f) => !f.is_future).map((f, i) => ({ seq: i + 1, features: f.features })), base) }));
};
const first = scoreAll(planes);
const cases = first.filter((x) => x.p.role === "repair-case").sort((a, b) => b.as.score - a.as.score);
const kept = new Set([...cases.slice(0, KEEP).map((x) => x.p.key), ...planes.filter((p) => p.role !== "repair-case").map((p) => p.key)]);
const fleet = planes.filter((p) => kept.has(p.key));

// Shuffle display order so repair cases aren't all first (deterministic).
fleet.sort((a, b) => hash(a.key) - hash(b.key));
const final = scoreAll(fleet);

console.log("\nAircraft            role          status  score  top finding                         real repair");
console.log("-".repeat(115));
final.forEach(({ p, as }, i) => {
  const top = as.findings[0];
  console.log(
    `SQK-${String(i + 1).padStart(2, "0")}  ${p.key.padEnd(11)} ${p.role.padEnd(13)} ${as.status.padEnd(7)} ${String(as.score).padEnd(6)} ${(top ? `${top.label} (${top.z}σ)` : "-").padEnd(36)} ${p.role === "repair-case" ? p.label : ""}`
  );
});
if (cases.length > KEEP) console.log(`\n(${cases.length - KEEP} weaker repair cases dropped. Use --keep N to change.)`);

// 3. SQL
const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const lines = ["-- Generated by scripts/build_seed.mjs from " + manifest.source, "DELETE FROM work_orders;", "DELETE FROM flights;", "DELETE FROM aircraft;"];
final.forEach(({ p }, i) => {
  const id = `SQK-${String(i + 1).padStart(2, "0")}`;
  const note = p.role === "repair-case" ? `NGAFID event ${p.event}: real unplanned repair "${p.label}" after these flights` : `NGAFID event ${p.event}: flights after a completed repair`;
  lines.push(`INSERT INTO aircraft (id, name, model, role, source_note) VALUES (${q(id)}, ${q(id)}, ${q(MODEL)}, ${q(p.role)}, ${q(note)});`);
  let seq = 0;
  for (const f of p.flights) {
    seq++;
    lines.push(
      `INSERT INTO flights (aircraft_id, seq, flown_at, features, is_future, source, ngafid_index, ngafid_before_after, ngafid_date_diff, ngafid_label) VALUES (${[
        q(id), seq, q(`Flight ${seq}`), q(JSON.stringify(f.features)), f.is_future ? 1 : 0, q(opt("source", "ngafid")), f.master_index, q(f.before_after), f.date_diff, q(p.role === "repair-case" ? f.label : null),
      ].join(", ")});`
    );
  }
});
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`\nWrote ${OUT}: ${final.length} aircraft, ${final.reduce((s, x) => s + x.p.flights.length, 0)} flights`);

function hash(s) {
  let h = 2166136261;
  for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return h >>> 0;
}
